#pragma once

#include "base.hpp"

#include <cmath>
#include <complex>

namespace epi::presets {

/**
 * Geometry & Number: Loxodromic Mobius Map, Rhumb Lines of the Sphere.
 *
 * Scientific foundation:
 * - A rhumb line (loxodrome, Nunes 1537) crosses every meridian at the same
 *   angle and winds round both poles without reaching them. On Mercator's
 *   chart it is straight; under stereographic projection it is a logarithmic
 *   spiral about each pole.
 * - Mobius maps fall into four conjugacy classes. The generic one is
 *   loxodromic: conjugate to w -> lambda w with |lambda| != 1 and lambda not
 *   real. Its orbits leave the repelling fixed point and arrive at the
 *   attracting one along double spirals, the rhumb lines of the sphere whose
 *   poles are the two fixed points. (The other classes appear in
 *   solc_filter_poincare_sphere_armillary, elliptic;
 *   loschmidt_echo_time_reversal_boost, hyperbolic; and at the band edge of
 *   spatial_wave_photonic_bandgap_smith_chart, parabolic.)
 *
 * Mapping to the 6-stage OpenCL / Vulkan pipeline:
 * - Inner = Invert, zn solved from the source p, the sink q and the
 *   multiplier lambda = 1.22 e^{0.62 i} at the source.
 * - The sink q is placed on the right edge of the frame, inside the Simplex
 *   seed band. Every orbit therefore ends in the seed, and a pixel's colour
 *   is set by how many steps it needs: the bands are the fundamental domains
 *   of the cyclic group generated by T, bounded by circular arcs, coiling
 *   out of the source as a spiral and straightening into the sink.
 * - Color = Alive with a log|T| term. log|T(z)| is the potential of a dipole
 *   (zero and pole of T), so the hue accumulated along an orbit also carries
 *   Apollonian shading across each band.
 * - The pole of T lies above the frame (near y = 1.9); its Torus-folded
 *   rings just reach the top edge.
 * - Motion: small shifts of zn2 and zn3. Any such shift leaves T a Mobius
 *   map, so the picture stays an exact loxodromic flow while the two poles
 *   wander.
 */
inline Pattern loxodromic_rhumb_line_double_spiral() {
  using C = std::complex<float>;
  constexpr float LAMBDA_ABS = 1.22f;
  constexpr float LAMBDA_ARG = 0.62f;

  const C source{-0.30f, 0.08f};
  const C sink{1.02f, -0.10f};
  const C mult{LAMBDA_ABS * std::cos(LAMBDA_ARG),
               LAMBDA_ABS * std::sin(LAMBDA_ARG)};
  // Mobius map with fixed points (source, sink) and multiplier mult at source.
  const C ma = source - sink * mult;
  const C mb = source * sink * (mult - 1.0f);
  const C mc = 1.0f - mult;
  const C md = mult * source - sink;
  const C post = (mb * mc - ma * md) / mc;
  const C shift = ma / mc;

  Pattern p;
  p.name = "loxodromic_rhumb_line_double_spiral";
  p.inner = InnerFunction::Invert;
  p.reduction = ReductionType::Torus;
  p.zn.zn[0] = {mc.real(), mc.imag()};
  p.zn.zn[1] = {md.real(), md.imag()};
  p.zn.zn[2] = {post.real(), post.imag()};
  p.zn.zn[3] = {shift.real(), shift.imag()};

  p.color.hue_rotation = 0.0f; // unused by Alive
  p.color.sat_scale = 1.10f;
  p.color.fade = 0.985f;
  p.color.color_mode = as_int(ColorMode::Alive);
  p.color.spiral_angle_coeff = 0.0f;
  p.color.spiral_radius_coeff = 0.04f; // dipole potential shading
  p.color.chroma_breath_amp = 0.0f;
  p.color.chroma_breath_freq = 0.1f;
  p.color.chroma_breath_phase = 0.0f;
  p.color.hue_velocity_base = 0.006f;
  p.color.hue_velocity_breath = 0.003f;
  p.color.hue_velocity_drift = 0.001f;
  p.color.luma_shape_depth = 0.0f;
  p.color.luma_shape_center = 0.0f;

  p.seed.type = SeedType::Simplex;
  p.seed.border_width = 0.09f;
  p.seed.hue = 0.08f;
  p.seed.hue_speed = 0.07f;
  p.seed.alpha = 0.92f;
  p.seed.pulse_freq = 0.06f;
  p.seed.pulse_amp = 0.10f;
  p.speed = 0.85f;

  p.motion
      .add("pole_wander_shift",
           control::ModLane{.wave = control::Waveform::Sine,
                            .frequency_hz = 0.023f,
                            .amplitude = 0.05f,
                            .offset = shift.imag()},
           control::ModTarget::Zn3Im)
      .add("pole_wander_post",
           control::ModLane{.wave = control::Waveform::Sine,
                            .frequency_hz = 0.031f,
                            .amplitude = 0.05f,
                            .offset = post.real()},
           control::ModTarget::Zn2Re)
      .add("potential_shading",
           control::ModLane{.wave = control::Waveform::Triangle,
                            .frequency_hz = 0.017f,
                            .amplitude = 0.025f,
                            .offset = 0.04f},
           control::ModTarget::SpiralRadiusCoeff);

  return p;
}

} // namespace epi::presets
