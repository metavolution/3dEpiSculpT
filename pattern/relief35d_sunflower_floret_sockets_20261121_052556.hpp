  Pattern p;
  p.name = "relief35d_sunflower_floret_sockets";
  p.inner = InnerFunction::Identity;
  p.reduction = ReductionType::Clamp;

  p.zn.zn[0] = {1.0f, 0.0f};
  p.zn.zn[1] = {0.0f, 0.0f};
  p.zn.zn[2] = {-0.7345668f, 0.6729235f};
  p.zn.zn[3] = {0.0f, 0.0f};

  p.color.color_mode = as_int(ColorMode::Classic);
  p.color.hue_rotation = 0.0f;
