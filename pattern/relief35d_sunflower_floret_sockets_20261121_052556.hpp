/**
 * Sunflower that remembers itself under its own golden turn.
 *
 * PhyllotaxisVogel seed (florets at r = c sqrt(n), angle 2 pi n alpha) fed
 * through a similarity memory z -> rho e^{i 2 pi (1 - alpha_golden)} z,
 * rho = 0.9962. For large n the golden turn maps floret n onto floret n+1
 * (radial mismatch sqrt(n/(n+1)) -> 1), so the outer head is a near-fixed
 * point of the memory and stays crisp, while the core, where the map is no
 * symmetry, smears into a whorl. Florets become sockets in the relief.
 *
 * Passport (research expedition 2026-11-21, docu/PLAN-preset-expedition-2026-11-21.md)
 *   Collection : 3.5D minimal
 *   Cell       : Identity / Clamp / PhyllotaxisVogel / Classic
 *   Height     : .w = age since a floret last lit this site [relief_35d observer]
 *   Why        : The feedback map is an approximate symmetry of the source: memory reinforces only where it is exact.
 *   Generated by tools/gen_expedition_presets.py (edit the roster there).
 */
