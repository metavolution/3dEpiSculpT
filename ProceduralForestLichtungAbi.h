/**
 * ============================================================================
 * EPI2 / 3dEpiSculpTMorph - PROCEDURAL FOREST LICHTUNG HOST/GPU ABI
 * ============================================================================
 *
 * [EDUCATIONAL NOTE: ALGORITHMIC NATURE & UNIFIED ECOLOGICAL FIELD ABI]
 * ----------------------------------------------------------------------------
 * Defines the fixed-layout, 16-byte aligned Host/OpenCL data contracts for the
 * Procedural Forest Lichtung ("Waldlichtung") subsystem:
 *   1. ForestWorldCellGpu (32B):
 *      Stores per-cell height H(x,z), irregular canopy clearing L(x,z),
 *      winding dirt path mask M_path(x,z), soil moisture, terrain slope,
 *      canopy openness (updated after tree placement), and terrain normal (nx, nz).
 *   2. ForestScatterInstanceGpu (32B):
 *      Compact ecological instance generated by stratified Poisson/blue-noise
 *      scattering across 7 ecological strata (Tree, Boulder, UnderstoryShrub,
 *      TallGrass, RootedWildflower, FernFrond, ForestDebris).
 *   3. ForestGroundFlowerGpu (64B):
 *      Stationary rooted wildflower state with Euler-Bernoulli cantilever stem
 *      sway, drooping 5-petal bell blossom frame, and cosine spectral HDR
 *      bioluminescence.
 *   4. ForestMossyBoulderGpu (32B) & ForestTreeGpu (32B):
 *      Geological ellipsoid SDF primitives and deciduous tree trunk/crown
 *      primitives for raymarching, canopy shadow transmittance, and mesh synthesis.
 *   5. ForestSwirlingPetalGpu (48B):
 *      Particle-fluid state for wind-advected Euler-Cromer curl-noise petal
 *      flurries with pink-to-violet chromodynamic age evolution.
 *   6. ForestLichtungDescriptorGpu (64B):
 *      Scene-wide geomorphology, wind, sunlight, and volumetric valley mist
 *      parameters shared between CPU reference evaluators and OpenCL kernels.
 * ============================================================================
 */

#pragma once

#include <cstddef>
#include <cstdint>

namespace epi_sculpt::forest {

enum class ForestLayerKind : std::uint32_t {
    Tree             = 0U,
    Boulder          = 1U,
    UnderstoryShrub  = 2U,
    TallGrass        = 3U,
    RootedWildflower = 4U,
    FernFrond        = 5U,
    ForestDebris     = 6U,
    Count            = 7U
};

enum class ForestMaterialId : std::int32_t {
    Sky           = 0,
    DirtPath      = 1,
    ForestFloor   = 2,
    MossyBoulder  = 3,
    TreeBark      = 4,
    FernFoliage   = 5,
    FlowerPetal   = 6,
    CanopyFoliage = 7
};

enum class ForestTreeSpecies : std::uint32_t {
    EuropeanBeech     = 0U, // Broad domed deciduous crown, smooth buttressed trunk
    SilverBirch       = 1U, // Slender trunk with dark lenticels, airy weeping crown
    MossyOak          = 2U, // Gnarled spreading limbs, deeply furrowed bark
    BlackForestSpruce = 3U, // Conical whorled evergreen tiers
    Count             = 4U
};

// 32-byte world field cell matching OpenCL WorldCell layout
struct alignas(16) ForestWorldCellGpu {
    float height = 0.0f;
    float clearing = 0.0f;
    float pathMask = 1.0f;   // 0 on trail centerline, 1 outside trail border
    float moisture = 0.5f;
    float slope = 0.0f;
    float openness = 0.5f;   // Sky/canopy visibility in [0, 1]
    float normalX = 0.0f;
    float normalZ = 0.0f;
};
static_assert(sizeof(ForestWorldCellGpu) == 32, "ForestWorldCellGpu must be exactly 32 bytes");

// 32-byte ecological scatter instance matching OpenCL Instance layout
struct alignas(16) ForestScatterInstanceGpu {
    float posX = 0.0f;
    float posY = 0.0f;
    float posZ = 0.0f;
    float scale = 1.0f;
    std::uint32_t kind = 0U;      // ForestLayerKind
    std::uint32_t species = 0U;   // 0..7 botanical/geological variant
    std::uint32_t seed = 0U;      // Deterministic instance hash seed
    std::uint32_t valid = 0U;     // 1 if accepted by ecological & Poisson masks
};
static_assert(sizeof(ForestScatterInstanceGpu) == 32, "ForestScatterInstanceGpu must be exactly 32 bytes");

// 64-byte rooted wildflower state with attached 5-fold cupped petals
struct alignas(16) ForestGroundFlowerGpu {
    float rootPosScale[4] = {0.0f, 0.0f, 0.0f, 0.35f};      // xyz = rooted ground anchor, w = stem length
    float headPosRadius[4] = {0.0f, 0.35f, 0.0f, 0.085f};   // xyz = deflected blossom center, w = blossom radius
    float headAxisStiffness[4] = {0.0f, -1.0f, 0.0f, 1.5f}; // xyz = drooping blossom axis, w = cantilever stiffness
    float glowColorPhase[4] = {0.8f, 0.4f, 0.9f, 0.25f};    // rgb = linear HDR petal emission, w = spectral hue seed [0,1)
};
static_assert(sizeof(ForestGroundFlowerGpu) == 64, "ForestGroundFlowerGpu must be exactly 64 bytes");

// 32-byte weathered granite boulder primitive
struct alignas(16) ForestMossyBoulderGpu {
    float centerRadius[4] = {0.0f, 0.0f, 0.0f, 1.2f}; // xyz = world center, w = base radius
    float stretchSeed[4] = {1.3f, 0.85f, 1.15f, 0.0f}; // xyz = anisotropic ellipsoid scale, w = geological cluster seed
};
static_assert(sizeof(ForestMossyBoulderGpu) == 32, "ForestMossyBoulderGpu must be exactly 32 bytes");

// 32-byte deciduous forest tree primitive
struct alignas(16) ForestTreeGpu {
    float baseRadius[4] = {0.0f, 0.0f, 0.0f, 0.35f};       // xyz = trunk root position, w = trunk base radius
    float canopyCenterRadius[4] = {0.0f, 6.5f, 0.0f, 3.8f}; // xyz = foliage crown center, w = crown radius
};
static_assert(sizeof(ForestTreeGpu) == 32, "ForestTreeGpu must be exactly 32 bytes");

// 48-byte wind-borne swirling flower petal particle state
struct alignas(16) ForestSwirlingPetalGpu {
    float positionAge[4] = {0.0f, 10.0f, 0.0f, 0.0f};   // xyz = world position, w = normalized age in [0, 1]
    float velocityDrag[4] = {0.0f, -1.2f, 0.0f, 1.8f};  // xyz = velocity (m/s), w = aerodynamic drag alpha
    float baseColorSeed[4] = {1.0f, 0.4f, 0.65f, 0.5f}; // rgb = current chromodynamic color, w = unique seed
};
static_assert(sizeof(ForestSwirlingPetalGpu) == 48, "ForestSwirlingPetalGpu must be exactly 48 bytes");

// 80-byte global Lichtung scene & atmospheric descriptor
struct alignas(16) ForestLichtungDescriptorGpu {
    float worldExtentXZ[2] = {80.0f, 80.0f};       // Total domain width and depth (meters)
    float clearingCenterXZ[2] = {0.0f, 12.0f};     // Center of the Waldlichtung canopy opening
    float clearingSemiAxesXZ[2] = {16.0f, 29.0f};  // Elliptical semi-axes (a, b) of the clearing
    float windVelocityXZ[2] = {0.65f, 0.25f};      // Ambient horizontal wind velocity (m/s)
    float sunDirection[4] = {0.42f, 0.78f, 0.46f, 0.0f}; // Normalized direction toward sun
    float sunRadiance[4] = {2.6f, 2.45f, 2.10f, 0.74f};  // rgb = sun HDR radiance, w = Henyey-Greenstein g
    float mistParams[4] = {0.018f, 0.12f, 3.2f, 0.0f};   // x = base density, y = height falloff, z = petal HDR gain, w = time
};
static_assert(sizeof(ForestLichtungDescriptorGpu) == 80, "ForestLichtungDescriptorGpu must be exactly 80 bytes");

// 32-byte 2D CSR Spatial Hash Grid header matching OpenCL ForestSpatialGridHeaderGpu
struct alignas(16) ForestSpatialGridHeaderGpu {
    std::uint32_t gridWidth = 16U;
    std::uint32_t gridHeight = 16U;
    float originX = -40.0f;
    float originZ = -40.0f;
    float invCellSize = 0.2f;
    float maxSceneElevation = 18.0f;
    std::uint32_t pad0 = 0U;
    std::uint32_t pad1 = 0U;
};
static_assert(sizeof(ForestSpatialGridHeaderGpu) == 32, "ForestSpatialGridHeaderGpu must be exactly 32 bytes");

} // namespace epi_sculpt::forest
